% Доп. задание 2: Генерация нормального распределения и расчёт асимметрии/эксцесса
mu = 0;  % Среднее нормального распределения
sigma = 1;  % Стандартное отклонение
N_norm = 1000;  % Размер выборки
sample_norm = normrnd(mu, sigma, N_norm, 1);

% Теоретические значения
skew_theory = 0;  % Асимметрия нормального распределения
kurt_theory = 3;  % Эксцесс нормального распределения

% Экспериментальные оценки
skew_exp = skewness(sample_norm);
kurt_exp = kurtosis(sample_norm);

% Вывод результатов
disp('Теоретические и экспериментальные значения:');
disp(['Асимметрия (теория): ' num2str(skew_theory) ', (эксперимент): ' num2str(skew_exp)]);
disp(['Эксцесс (теория): ' num2str(kurt_theory) ', (эксперимент): ' num2str(kurt_exp)]);

% Доп. задание 3: Оценка нормальности
[h, p] = kstest(sample_norm);  % Тест Колмогорова-Смирнова
disp(['p-значение теста нормальности: ' num2str(p)]);
if h == 0
    disp('Выборка не противоречит нормальному распределению (p > 0.05)');
else
    disp('Выборка противоречит нормальному распределению (p <= 0.05)');
end

% Q-Q-плот с обозначениями
figure;
qqplot(sample_norm);
title('Q-Q Plot для нормального распределения');
xlabel('Теоретические квантили');
ylabel('Выборочные квантили');
legend('Sample Quantiles', 'Theoretical Quantiles', 'Location', 'best');